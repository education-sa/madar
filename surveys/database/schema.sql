-- Additive migration. MySQL 8 / MariaDB 10.6+, InnoDB, utf8mb4.
CREATE TABLE IF NOT EXISTS ms_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 external_id VARCHAR(191) COLLATE utf8mb4_bin NULL UNIQUE,
 name VARCHAR(160) NOT NULL, email VARCHAR(191) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NULL, verified_at DATETIME NULL,
 active TINYINT NOT NULL DEFAULT 1, is_admin TINYINT NOT NULL DEFAULT 0,
 school_name VARCHAR(200) NOT NULL DEFAULT '', logo_key CHAR(36) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ms_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 purpose VARCHAR(20) NOT NULL, expires_at DATETIME NOT NULL,
 FOREIGN KEY(user_id) REFERENCES ms_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ms_surveys (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL, title VARCHAR(200) NOT NULL,
 lesson VARCHAR(250) NOT NULL DEFAULT '', school_name VARCHAR(200) NOT NULL,
 logo_key CHAR(36) NULL, use_default_logo TINYINT NOT NULL DEFAULT 0,
 kind VARCHAR(20) NOT NULL, performance TINYINT NOT NULL DEFAULT 1,
 status VARCHAR(20) NOT NULL DEFAULT 'draft', share_token CHAR(48) NOT NULL UNIQUE,
 definition JSON NOT NULL, revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_id) REFERENCES ms_users(id), INDEX(owner_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ms_responses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 survey_id BIGINT UNSIGNED NOT NULL, reviewer_id BIGINT UNSIGNED NOT NULL,
 answers JSON NOT NULL, notes TEXT NOT NULL,
 submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY ms_one_response(survey_id,reviewer_id),
 FOREIGN KEY(survey_id) REFERENCES ms_surveys(id),
 FOREIGN KEY(reviewer_id) REFERENCES ms_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ms_templates (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(200) NOT NULL, kind VARCHAR(20) NOT NULL,
 definition JSON NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ms_settings (
 setting_key VARCHAR(60) PRIMARY KEY, setting_value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
